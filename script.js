const storiesGrid = document.getElementById("stories-grid");


// Create each story card
stories.forEach((story) => {

    const card = document.createElement("article");

    card.classList.add("story-card");

    card.innerHTML = `
        <img
            src="${story.imageURL}"
            alt="${story.title}"
            class="story-image"
        >

        <div class="story-card-content">

            <div class="story-meta">
                <span class="pub-tag">${story.publication}</span>
                <span class="year-tag">${story.year}</span>
            </div>

            <h3>${story.title}</h3>

            <span class="view-story">
                View Story →
            </span>

        </div>
    `;

    storiesGrid.appendChild(card);


    // ==========================================
    // OPEN MODAL
    // ==========================================

    card.addEventListener("click", () => {

        document.getElementById("modal-image").src = story.imageURL;

        document.getElementById("modal-image").alt = story.title;

        document.getElementById("modal-publication").innerText =
            story.publication;

        document.getElementById("modal-year").innerText =
            story.year;

        document.getElementById("modal-title").innerText =
            story.title;

        document.getElementById("modal-overview").innerHTML =
            story.overview;

        document.getElementById("modal-link").href =
            story.articleLink;

        document.getElementById("story-modal").style.display = "flex";

        document.body.classList.add("modal-open");

    });

});


// ==========================================
// MODAL ELEMENTS
// ==========================================

const modal = document.getElementById("story-modal");

const closeModalBtn =
    document.getElementById("close-modal");


// ==========================================
// CLOSE MODAL — X BUTTON
// ==========================================

closeModalBtn.addEventListener("click", () => {

    modal.style.display = "none";

    document.body.classList.remove("modal-open");

});


// ==========================================
// CLOSE MODAL — CLICK OUTSIDE
// ==========================================

window.addEventListener("click", (event) => {

    if (event.target === modal) {

        modal.style.display = "none";

        document.body.classList.remove("modal-open");

    }

});


// ==========================================
// CLOSE MODAL — ESCAPE KEY
// ==========================================

document.addEventListener("keydown", (event) => {

    if (
        event.key === "Escape" &&
        modal.style.display === "flex"
    ) {

        modal.style.display = "none";

        document.body.classList.remove("modal-open");

    }

});


// ==========================================
// SMOOTH SCROLLING FOR NAVIGATION
// ==========================================

document.querySelectorAll('a[href^="#"]').forEach((anchor) => {

    anchor.addEventListener("click", function (event) {

        const targetID = this.getAttribute("href");

        if (targetID === "#") {
            return;
        }

        const target = document.querySelector(targetID);

        if (target) {

            event.preventDefault();

            target.scrollIntoView({
                behavior: "smooth",
                block: "start"
            });

        }

    });

});